"""Synthetic Poll Dataset Generator.

=============================================================================
DISCLAIMER:
All data generated by this script is 100% synthetic, simulated, and intended
solely for educational, exploratory, and portfolio demonstration purposes.
It does NOT represent real people, real survey participants, actual academic
departments, or genuine survey findings.
Zero personally identifiable information (PII) is generated or stored.
=============================================================================
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Optional

import numpy as np
import pandas as pd


# Controlled domain categories
DEPARTMENTS = ["IT", "Commerce", "Science", "Arts"]
STUDY_YEARS = [1, 2, 3, 4]
PREFERRED_LANGUAGES = ["Python", "Java", "C++", "JavaScript"]
TRAINING_SATISFACTION_SCORES = [1, 2, 3, 4, 5]
LEARNING_METHODS = [
    "Hands-on Projects",
    "Video Tutorials",
    "Classroom Lectures",
    "Online Courses",
]
INTERNSHIP_INTEREST_CHOICES = ["Yes", "No"]
RECOMMENDATION_SCORES = list(range(0, 11))  # 0 through 10 inclusive

# Plausible synthetic survey comments (some respondents leave optional feedback)
SAMPLE_FEEDBACK_COMMENTS = [
    "Practical exercises were very helpful for understanding core concepts.",
    "Pacing was slightly fast in the middle modules, but overall great content.",
    "Loved the hands-on project assignments.",
    "More live coding demonstrations would be appreciated.",
    "Well-structured modules and clear explanations.",
    "The tutorials helped bridge theoretical lectures with practice.",
    "Would love additional real-world case studies in upcoming sessions.",
    "Clear, concise, and engaging presentations throughout.",
    "Interactive quizzes helped reinforce weekly topics.",
    "Great introductory pace for beginners.",
    "Session notes and documentation were comprehensive.",
    "Could benefit from more advanced challenge exercises.",
]


def generate_synthetic_poll_data(
    num_samples: int = 500,
    random_seed: int = 42,
    output_path: Optional[str | Path] = None,
    overwrite: bool = True,
) -> pd.DataFrame:
    """Generate a reproducible synthetic poll dataset and optionally save it to disk.

    Args:
        num_samples: Total number of survey records to generate (default: 500).
        random_seed: Seed for numpy pseudo-random number generator (default: 42).
        output_path: Target path for the output CSV. If None, defaults to
                     'data/raw/sample_poll_data.csv'.
        overwrite: Whether to overwrite the destination CSV if it already exists.

    Returns:
        pd.DataFrame containing the 9 expected synthetic survey columns.
    """
    if output_path is None:
        target_file = Path("data") / "raw" / "sample_poll_data.csv"
    else:
        target_file = Path(output_path)

    # Inspect destination before generation
    if target_file.exists():
        if overwrite:
            print(f"[Notice] Target file '{target_file}' already exists. Overwriting with newly generated data.")
        else:
            print(f"[Notice] Target file '{target_file}' exists and overwrite=False. Aborting save.")
            return pd.read_csv(target_file)

    rng = np.random.default_rng(random_seed)

    # 1. Unique Response IDs
    response_ids = [f"RESP_{i + 1:04d}" for i in range(num_samples)]

    # 2. Department (Plausible distribution across 4 disciplines)
    dept_probs = [0.36, 0.26, 0.22, 0.16]
    departments = rng.choice(DEPARTMENTS, size=num_samples, p=dept_probs)

    # 3. Study Year (Integers 1 to 4)
    year_probs = [0.32, 0.28, 0.22, 0.18]
    study_years = rng.choice(STUDY_YEARS, size=num_samples, p=year_probs)

    # 4. Preferred Language
    lang_probs = [0.42, 0.24, 0.18, 0.16]
    languages = rng.choice(PREFERRED_LANGUAGES, size=num_samples, p=lang_probs)

    # 5. Training Satisfaction (Integers 1 to 5)
    sat_probs = [0.06, 0.12, 0.28, 0.36, 0.18]
    satisfaction = rng.choice(TRAINING_SATISFACTION_SCORES, size=num_samples, p=sat_probs)

    # 6. Preferred Learning Method
    method_probs = [0.44, 0.26, 0.16, 0.14]
    learning_methods = rng.choice(LEARNING_METHODS, size=num_samples, p=method_probs)

    # 7. Internship Interest (Yes/No)
    internship_probs = [0.74, 0.26]
    internship_interest = rng.choice(INTERNSHIP_INTEREST_CHOICES, size=num_samples, p=internship_probs)

    # 8. Recommendation Score (Integers 0 to 10)
    rec_probs = [0.02, 0.02, 0.03, 0.04, 0.06, 0.11, 0.14, 0.18, 0.20, 0.12, 0.08]
    rec_scores = rng.choice(RECOMMENDATION_SCORES, size=num_samples, p=rec_probs)

    # 9. Comments (Optional: ~45% left empty/null, rest populated from plausible feedback)
    comments: list[Optional[str]] = []
    feedback_array = np.array(SAMPLE_FEEDBACK_COMMENTS)
    for _ in range(num_samples):
        # 45% chance of leaving comment blank
        if rng.random() < 0.45:
            comments.append(None)
        else:
            comments.append(str(rng.choice(feedback_array)))

    df = pd.DataFrame(
        {
            "response_id": response_ids,
            "department": departments,
            "study_year": study_years,
            "preferred_language": languages,
            "training_satisfaction": satisfaction,
            "preferred_learning_method": learning_methods,
            "internship_interest": internship_interest,
            "recommendation_score": rec_scores,
            "comments": comments,
        }
    )

    # Ensure parent output directory exists
    target_file.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(target_file, index=False)
    print(f"[Success] Generated {len(df)} synthetic records saved to '{target_file}' (Seed: {random_seed}).")

    return df


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Generate synthetic poll response data for Poll Results Visualizer."
    )
    parser.add_argument(
        "--samples",
        type=int,
        default=500,
        help="Number of synthetic survey responses to generate (default: 500).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for deterministic generation (default: 42).",
    )
    parser.add_argument(
        "--output",
        type=str,
        default="data/raw/sample_poll_data.csv",
        help="Destination path for generated CSV (default: data/raw/sample_poll_data.csv).",
    )
    parser.add_argument(
        "--no-overwrite",
        action="store_true",
        help="Prevent overwriting if destination file already exists.",
    )

    args = parser.parse_args()

    df = generate_synthetic_poll_data(
        num_samples=args.samples,
        random_seed=args.seed,
        output_path=args.output,
        overwrite=not args.no_overwrite,
    )

    print("\n--- Synthetic Dataset Summary ---")
    print(f"Shape: {df.shape[0]} rows x {df.shape[1]} columns")
    print(f"Columns: {list(df.columns)}")
    print("\nMissing Values:")
    print(df.isnull().sum())
    print("\nFirst 3 rows preview:")
    print(df.head(3))


if __name__ == "__main__":
    main()
